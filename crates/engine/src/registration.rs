//! Registering Quorum in an organisation's Microsoft Entra tenant.
//!
//! Each organisation registers Quorum once in its own tenant (a public client: no secret,
//! delegated permissions only), so the IT admin approves exactly what Quorum may do and no data
//! passes through anyone else. This module generates the setup scripts (`quorum-cli
//! setup-tenant`, committed as `scripts/register-quorum.sh` / `.ps1`), the admin-consent link
//! and the one-click setup link users open to configure the app.
//!
//! The scripts use only the Azure CLI (`az`), resolve Microsoft Graph permission ids at run time
//! (never hard-coded GUIDs) and refuse to finish if any permission is unknown.

use std::fmt::Write as _;

use crate::account::REQUIRED_SCOPES;

/// Microsoft Graph's application id.
pub const GRAPH_APP_ID: &str = "00000003-0000-0000-c000-000000000000";
/// Sign-in scopes requested alongside the Graph permissions.
pub const SIGN_IN_SCOPES: &[&str] = &["openid", "profile", "email", "offline_access"];
/// Graph permissions the registration lists beyond [`REQUIRED_SCOPES`]: covered by broader
/// ones today, listed so the admin sees the intent (`plan/graph-permissions.md`).
pub const EXTRA_SCOPES: &[&str] =
    &["Calendars.ReadBasic", "ChatMember.ReadWrite", "ChannelMember.Read.All", "TeamMember.Read.All", "Notes.Read.All"];
/// The redirect URI of the browser sign-in (any loopback port is accepted for it).
pub const REDIRECT_URI: &str = "http://localhost";

/// Every delegated permission the app registration asks for, in a stable order.
#[must_use]
pub fn registration_scopes() -> Vec<&'static str> {
    let mut out: Vec<&'static str> = Vec::new();
    for s in SIGN_IN_SCOPES.iter().chain(REQUIRED_SCOPES).chain(EXTRA_SCOPES) {
        if !out.contains(s) {
            out.push(s);
        }
    }
    out
}

/// Whether `id` looks like a tenant or client id we can put in a URL (GUID-ish or a domain).
fn safe_id(id: &str) -> bool {
    !id.is_empty() && id.len() <= 128 && id.chars().all(|c| c.is_ascii_alphanumeric() || "-._".contains(c))
}

/// The link an admin opens to approve Quorum for the whole organisation.
#[must_use]
pub fn admin_consent_url(tenant: &str, client_id: &str) -> Option<String> {
    (safe_id(tenant) && safe_id(client_id))
        .then(|| format!("https://login.microsoftonline.com/{tenant}/adminconsent?client_id={client_id}"))
}

/// The one-click link that opens Quorum with the organisation's ids filled in.
#[must_use]
pub fn setup_link(tenant: &str, client_id: &str) -> Option<String> {
    (safe_id(tenant) && safe_id(client_id)).then(|| format!("quorum://setup?tenant={tenant}&client_id={client_id}"))
}

/// JMESPath literal array of the scopes, for `az --query`.
fn jmes_list(scopes: &[&str]) -> String {
    let quoted: Vec<String> = scopes.iter().map(|s| format!("\"{s}\"")).collect();
    format!("[{}]", quoted.join(","))
}

/// The bash setup script (macOS, Linux, Azure Cloud Shell).
#[must_use]
pub fn bash_script() -> String {
    let scopes = registration_scopes();
    let mut s = String::new();
    let _ = write!(
        s,
        r#"#!/usr/bin/env bash
# Registers Quorum in your organisation's Microsoft Entra tenant.
#
# Generated by `quorum-cli setup-tenant --shell bash`; do not edit by hand.
# Needs the Azure CLI (https://aka.ms/azcli) and an account that may create app registrations
# (Application Developer or higher). Granting consent needs Cloud Application Administrator or
# Global Administrator; without it the script prints a link for your admin.
#
# Usage: bash register-quorum.sh [display name]     (default name: Quorum)
# Works in Azure Cloud Shell (shell.azure.com) without installing anything.
set -euo pipefail

APP_NAME="${{1:-Quorum}}"
GRAPH="{GRAPH_APP_ID}"
EXPECTED={count}
QUERY='oauth2PermissionScopes[?contains(`{list}`, value)].{{id: id, type: `"Scope"`}}'

command -v az >/dev/null 2>&1 || {{ echo "Install the Azure CLI first: https://aka.ms/azcli (or run this in Azure Cloud Shell)." >&2; exit 1; }}
az account show >/dev/null 2>&1 || az login --allow-no-subscriptions >/dev/null
TENANT="$(az account show --query tenantId -o tsv)"
echo "Registering \"$APP_NAME\" in tenant $TENANT"

ACCESS="$(az ad sp show --id "$GRAPH" --query "$QUERY" -o json)"
FOUND="$(printf '%s' "$ACCESS" | grep -o '"id"' | wc -l | tr -d ' ')"
if [ "$FOUND" != "$EXPECTED" ]; then
  echo "Microsoft Graph returned $FOUND of $EXPECTED permissions; stopping without changes." >&2
  exit 1
fi
REQUIRED="[{{\"resourceAppId\":\"$GRAPH\",\"resourceAccess\":$ACCESS}}]"

CLIENT="$(az ad app create \
  --display-name "$APP_NAME" \
  --sign-in-audience AzureADMyOrg \
  --public-client-redirect-uris {REDIRECT_URI} \
  --is-fallback-public-client true \
  --required-resource-accesses "$REQUIRED" \
  --query appId -o tsv)"
az ad sp create --id "$CLIENT" >/dev/null
echo "Created the app registration and its service principal."

CONSENT="https://login.microsoftonline.com/$TENANT/adminconsent?client_id=$CLIENT"
echo "Granting admin consent (waits a moment for Entra to catch up)..."
sleep 20
if az ad app permission admin-consent --id "$CLIENT" >/dev/null 2>&1; then
  echo "Admin consent granted for the whole organisation."
else
  echo "Couldn't grant consent with this account. An admin should open:"
  echo "  $CONSENT"
fi

echo
echo "Directory (tenant) ID:    $TENANT"
echo "Application (client) ID: $CLIENT"
echo
echo "Send your users this link; it opens Quorum with both IDs filled in:"
echo "  quorum://setup?tenant=$TENANT&client_id=$CLIENT"
"#,
        count = scopes.len(),
        list = jmes_list(&scopes),
    );
    s
}

/// The PowerShell setup script (Windows; needs the Azure CLI too).
#[must_use]
pub fn powershell_script() -> String {
    let scopes = registration_scopes();
    let mut s = String::new();
    let _ = write!(
        s,
        r#"# Registers Quorum in your organisation's Microsoft Entra tenant.
#
# Generated by `quorum-cli setup-tenant --shell powershell`; do not edit by hand.
# Needs the Azure CLI (https://aka.ms/azcli) and an account that may create app registrations
# (Application Developer or higher). Granting consent needs Cloud Application Administrator or
# Global Administrator; without it the script prints a link for your admin.
#
# Usage: pwsh ./register-quorum.ps1 [-AppName Quorum]
param([string]$AppName = "Quorum")
$ErrorActionPreference = "Stop"

$Graph = "{GRAPH_APP_ID}"
$Expected = {count}
$Query = 'oauth2PermissionScopes[?contains(`{list}`, value)].{{id: id, type: `"Scope"`}}'

if (-not (Get-Command az -ErrorAction SilentlyContinue)) {{ throw "Install the Azure CLI first: https://aka.ms/azcli" }}
az account show *> $null
if ($LASTEXITCODE -ne 0) {{ az login --allow-no-subscriptions | Out-Null }}
$Tenant = az account show --query tenantId -o tsv
Write-Host "Registering ""$AppName"" in tenant $Tenant"

$Access = az ad sp show --id $Graph --query $Query -o json | Out-String
$Found = ([regex]::Matches($Access, '"id"')).Count
if ($Found -ne $Expected) {{ throw "Microsoft Graph returned $Found of $Expected permissions; stopping without changes." }}
$Required = "[{{""resourceAppId"":""$Graph"",""resourceAccess"":$($Access.Trim())}}]"
$RequiredFile = New-TemporaryFile
Set-Content -Path $RequiredFile -Value $Required -Encoding utf8

$Client = az ad app create `
  --display-name $AppName `
  --sign-in-audience AzureADMyOrg `
  --public-client-redirect-uris {REDIRECT_URI} `
  --is-fallback-public-client true `
  --required-resource-accesses "@$RequiredFile" `
  --query appId -o tsv
Remove-Item $RequiredFile
az ad sp create --id $Client | Out-Null
Write-Host "Created the app registration and its service principal."

$Consent = "https://login.microsoftonline.com/$Tenant/adminconsent?client_id=$Client"
Write-Host "Granting admin consent (waits a moment for Entra to catch up)..."
Start-Sleep -Seconds 20
az ad app permission admin-consent --id $Client *> $null
if ($LASTEXITCODE -eq 0) {{
  Write-Host "Admin consent granted for the whole organisation."
}} else {{
  Write-Host "Couldn't grant consent with this account. An admin should open:"
  Write-Host "  $Consent"
}}

Write-Host ""
Write-Host "Directory (tenant) ID:    $Tenant"
Write-Host "Application (client) ID: $Client"
Write-Host ""
Write-Host "Send your users this link; it opens Quorum with both IDs filled in:"
Write-Host "  quorum://setup?tenant=$Tenant&client_id=$Client"
"#,
        count = scopes.len(),
        list = jmes_list(&scopes),
    );
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scopes_are_unique_and_include_sign_in_and_features() {
        let scopes = registration_scopes();
        let mut sorted = scopes.clone();
        sorted.sort_unstable();
        sorted.dedup();
        assert_eq!(sorted.len(), scopes.len());
        for s in ["openid", "offline_access", "Mail.ReadWrite", "Presence.ReadWrite", "Notes.Read.All"] {
            assert!(scopes.contains(&s), "{s}");
        }
        assert!(scopes.iter().all(|s| s.chars().all(|c| c.is_ascii_alphanumeric() || c == '.' || c == '_')));
    }

    #[test]
    fn links_are_built_only_from_safe_ids() {
        let t = "11111111-2222-3333-4444-555555555555";
        assert_eq!(
            admin_consent_url(t, "abc").as_deref(),
            Some("https://login.microsoftonline.com/11111111-2222-3333-4444-555555555555/adminconsent?client_id=abc")
        );
        assert!(setup_link(t, "abc").is_some_and(|l| l.starts_with("quorum://setup?tenant=")));
        for bad in ["", "a b", "x&y=1", "a/b", &"a".repeat(200)] {
            assert!(admin_consent_url(bad, "abc").is_none(), "{bad}");
            assert!(setup_link(t, bad).is_none(), "{bad}");
        }
    }

    #[test]
    fn scripts_list_every_scope_and_match_the_committed_copies() {
        let (bash, ps) = (bash_script(), powershell_script());
        for s in registration_scopes() {
            assert!(bash.contains(&format!("\"{s}\"")) && ps.contains(&format!("\"{s}\"")), "{s}");
        }
        assert!(bash.contains(&format!("EXPECTED={}", registration_scopes().len())));
        // The copies admins download from the repository must be what the CLI prints.
        assert_eq!(
            include_str!("../../../scripts/register-quorum.sh"),
            bash,
            "run `quorum-cli setup-tenant --shell bash > scripts/register-quorum.sh`"
        );
        assert_eq!(
            include_str!("../../../scripts/register-quorum.ps1"),
            ps,
            "run `quorum-cli setup-tenant --shell powershell > scripts/register-quorum.ps1`"
        );
    }

    #[test]
    fn setup_guide_lists_every_scope() {
        let guide = include_str!("../../../docs/setup-tenant.md");
        for s in registration_scopes() {
            assert!(guide.contains(s), "docs/setup-tenant.md is missing {s}");
        }
    }
}
